# frozen_string_literal: true

require "fileutils"
require "open3"

module RailsVis
  # Writes .github/workflows/rails_vis.yml (dump + GitHub Pages deploy) and links the page from README.md.
  # Only the secret's name appears in the workflow, never a value.
  class Install
    WORKFLOW = ".github/workflows/rails_vis.yml"

    def initialize(root:, repo:, io: $stdout, force: false)
      @root = Pathname.new(root.to_s)
      @repo = repo
      @io = io
      @force = force
    end

    # Returns the paths written, relative to the root.
    def call
      written = []
      written << WORKFLOW if write_workflow
      written << "README.md" if write_readme
      written
    end

    private

    def write_workflow
      path = @root.join(WORKFLOW)
      if path.exist? && !@force
        @io.puts "#{WORKFLOW} exists; FORCE=1 to overwrite"
        return false
      end
      FileUtils.mkdir_p(path.dirname)
      path.write(workflow)
      @io.puts "Enable GitHub Pages with source 'GitHub Actions' in the repository settings."
      true
    end

    def write_readme
      unless @repo.owner
        @io.puts "README not updated: no GitHub origin"
        return false
      end
      path = @root.join("README.md")
      text = path.exist? ? path.read : ""
      return false if text.include?("github.io/#{@repo.repo}/")

      text += "\n" unless text.empty? || text.end_with?("\n")
      text += "\n" unless text.empty?
      path.write(text + "- [Onboarding dashboard](https://#{@repo.owner}.github.io/#{@repo.repo}/) generated by the rails_vis workflow on every push to #{branch}.\n")
      true
    end

    def branch
      @branch ||= begin
        out, status = Open3.capture2("git", "-C", @root.to_s, "symbolic-ref", "--short", "refs/remotes/origin/HEAD", err: File::NULL)
        name = out.strip.delete_prefix("origin/")
        status.success? && !name.empty? ? name : "main"
      rescue SystemCallError
        "main"
      end
    end

    def postgres?
      file = @root.join("config/database.yml")
      file.file? && file.read.match?(/^\s*adapter:\s*["']?postgres/)
    end

    def vips?
      file = @root.join("Gemfile.lock")
      file.file? && file.read.match?(/^\s+ruby-vips \(/)
    end

    def workflow
      <<~YAML
        # Generated by bin/rails rails_vis:install. Dumps the onboarding dashboard and publishes it to GitHub Pages.
        name: rails_vis

        on:
          push:
            branches: [#{branch}]
          workflow_dispatch:

        permissions:
          contents: read
          pages: write
          id-token: write

        concurrency:
          group: rails_vis-pages
          cancel-in-progress: true

        jobs:
          dump:
            runs-on: ubuntu-latest
        #{postgres? ? POSTGRES_SERVICE : ""}    env:
              RAILS_ENV: development
              RAILS_MASTER_KEY: ${{ secrets.RAILS_MASTER_KEY }}
        #{postgres? ? "      DATABASE_URL: postgres://postgres:postgres@localhost:5432/rails_vis\n" : ""}    steps:
              - uses: actions/checkout@v4
              - uses: ruby/setup-ruby@v1
                with:
                  bundler-cache: true
        #{vips? ? "      - name: Install libvips\n        run: sudo apt-get update && sudo apt-get install -y libvips\n" : ""}      - run: bin/rails db:prepare
              - run: bin/rails rails_vis:dump
              - uses: actions/configure-pages@v5
              - uses: actions/upload-pages-artifact@v3
                with:
                  path: doc/rails_vis
          deploy:
            needs: dump
            runs-on: ubuntu-latest
            environment:
              name: github-pages
              url: ${{ steps.deployment.outputs.page_url }}
            steps:
              - id: deployment
                uses: actions/deploy-pages@v4
      YAML
    end

    POSTGRES_SERVICE = <<~YAML.gsub(/^/, "    ")
      services:
        postgres:
          image: postgres:16
          env:
            POSTGRES_PASSWORD: postgres
          ports:
            - 5432:5432
          options: >-
            --health-cmd "pg_isready -U postgres"
            --health-interval 10s
            --health-timeout 5s
            --health-retries 5
    YAML
  end
end
